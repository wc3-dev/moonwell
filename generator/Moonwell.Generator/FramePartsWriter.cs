using System.Text;
using System.Text.RegularExpressions;

namespace Moonwell.Generator;

/// <summary>
/// Writes the analyzer's list of the game's Strings and Textures (MW0057): the named <c>String</c> and <c>Texture</c>
/// blocks of the game's <c>.fdf</c> files, each with the frame that draws it, which the game crashes on given some
/// frame natives (J17). A name the files also give a <c>Frame</c> is left out, as it may be that frame.
/// </summary>
public static partial class FramePartsWriter
{
    /// <summary>Each String's and Texture's name, its kind, and the frame it sits in (null for a template at the top, or
    /// when the files put it in more than one).</summary>
    public static SortedDictionary<string, (string Kind, string? Frame)> Read(IEnumerable<string> files)
    {
        var parts = new SortedDictionary<string, (string Kind, string? Frame)>(StringComparer.Ordinal);
        var frames = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        foreach (var file in files)
        {
            // Each open block: the frame's name for a Frame, else null.
            var open = new Stack<string?>();
            foreach (Match token in Token().Matches(Comment().Replace(file, "")))
            {
                if (token.Groups["frame"].Success)
                {
                    frames.Add(token.Groups["frame"].Value);
                    open.Push(token.Groups["frame"].Value);
                }
                else if (token.Groups["part"].Success)
                {
                    var name = token.Groups["part"].Value;
                    var owner = open.FirstOrDefault(frame => frame != null);
                    parts[name] = parts.TryGetValue(name, out var seen) && seen.Frame != owner
                        ? (token.Groups["kind"].Value, null)
                        : (token.Groups["kind"].Value, owner);
                    open.Push(null);
                }
                else if (token.Value == "{")
                {
                    open.Push(null);
                }
                else if (token.Value == "}" && open.Count > 0)
                {
                    open.Pop();
                }
            }
        }

        foreach (var frame in frames)
        {
            parts.Remove(frame);
        }

        return parts;
    }

    public static string Write(SortedDictionary<string, (string Kind, string? Frame)> parts, string gameVersion)
    {
        var text = new StringBuilder($"// Generated by Moonwell.Generator from the game's UI/FrameDef .fdf files, game {gameVersion}. Do not edit.\n");
        text.Append("\n#nullable enable\n\nusing System;\nusing System.Collections.Generic;\n\nnamespace Moonwell.Analyzers\n{\n");
        text.Append("    /// <summary>The game's named Strings and Textures, which <c>BlzGetFrameByName</c> finds and some frame natives crash on (MW0057): each its kind and the frame it sits in, or null.</summary>\n");
        text.Append("    internal static class GameFrameParts\n    {\n");
        text.Append("        public static readonly Dictionary<string, (string Kind, string? Frame)> All = new(StringComparer.OrdinalIgnoreCase)\n        {\n");
        foreach (var (name, (kind, frame)) in parts)
        {
            text.Append($"            [\"{name}\"] = (\"{kind}\", {(frame == null ? "null" : $"\"{frame}\"")}),\n");
        }

        text.Append("        };\n    }\n}\n");
        return text.ToString();
    }

    [GeneratedRegex(@"//[^\n]*")]
    private static partial Regex Comment();

    // A Frame's or a String's or Texture's opening (with INHERITS), a quoted text (skipped, as it may hold a brace), or a brace.
    [GeneratedRegex("""
        \bFrame\s*"[^"]*"\s*"(?<frame>[^"]+)"(?:\s+INHERITS\s+(?:WITHCHILDREN\s+)?"[^"]*")?\s*\{
        |\b(?<kind>String|Texture)\s+"(?<part>[^"]+)"(?:\s+INHERITS\s+(?:WITHCHILDREN\s+)?"[^"]*")?\s*\{
        |"[^"]*"
        |[{}]
        """, RegexOptions.IgnorePatternWhitespace)]
    private static partial Regex Token();
}
