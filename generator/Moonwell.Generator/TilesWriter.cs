using System.Text;
using Moonwell.GameData;

namespace Moonwell.Generator;

/// <summary>Writes the terrain package's Tile class: a constant for every ground tile in the game's Terrain.slk.</summary>
public static class TilesWriter
{
    public static string Write(IReadOnlyList<MetaRow> rows, string gameVersion)
    {
        var text = new StringBuilder($"// Generated by Moonwell.Generator from the game's TerrainArt/Terrain.slk, game {gameVersion}. Do not edit.\n");
        text.Append("\nnamespace Moonwell\n{\n");
        text.Append("    /// <summary>The game's ground tiles, for <c>Terrain.SetTile</c> and <c>Terrain.Tile</c>: each its four-letter id as a number. The game draws only the tiles in the map's own list, which the map class's Tiles adds to.</summary>\n");
        text.Append("    public static class Tile\n    {\n");
        var used = new HashSet<string>(StringComparer.Ordinal);
        foreach (var row in rows)
        {
            var id = row.Id;
            var dir = row.Columns["dir"];
            var tileset = dir.Substring(dir.LastIndexOf('\\') + 1);
            var comment = row.Columns["comment"];
            // An id starting with c is the ground drawn on a cliff's side, a second tile under the same name.
            var name = tileset + Pascal(comment) + (id[0] == 'c' ? "Cliff" : "");
            if (!used.Add(name))
            {
                throw new InvalidOperationException($"Two tiles are named {name}; the second is {id}");
            }

            var number = (id[0] << 24) | (id[1] << 16) | (id[2] << 8) | id[3];
            text.Append($"        /// <summary>{Spaced(tileset)}: {comment.Replace("  ", " ")} (<c>{id}</c>).</summary>\n");
            text.Append($"        public const int {name} = {number};\n\n");
        }

        text.Length -= 1;
        text.Append("    }\n}\n");
        return text.ToString();
    }

    private static string Pascal(string words)
    {
        var text = new StringBuilder();
        foreach (var word in words.Split(' ', StringSplitOptions.RemoveEmptyEntries))
        {
            var letters = new string(word.Where(char.IsLetterOrDigit).ToArray());
            if (letters.Length > 0)
            {
                text.Append(char.ToUpperInvariant(letters[0])).Append(letters, 1, letters.Length - 1);
            }
        }

        return text.ToString();
    }

    private static string Spaced(string pascal)
    {
        var text = new StringBuilder();
        foreach (var character in pascal)
        {
            if (char.IsUpper(character) && text.Length > 0)
            {
                text.Append(' ');
            }

            text.Append(character);
        }

        return text.ToString();
    }
}
