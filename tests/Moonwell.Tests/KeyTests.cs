    [Fact]
    public void every_code_is_one_of_the_games()
    {
        var values = Enum.GetValues<Key>().Select(key => (int)key).ToList();
        Assert.Equal(183, GameCodes.Length);
        Assert.Equal(values.Count, values.Distinct().Count());
        Assert.Equal(GameCodes.OrderBy(code => code), values.OrderBy(code => code));
    }

    // The game's side registers the keys from its own list of codes, as Lua has no Enum.GetValues.
    [Fact]
    public void the_native_world_listens_for_every_key()
    {
        var values = Enum.GetValues<Key>().Select(key => (int)key).OrderBy(code => code);
        Assert.Equal(values, Moonwell.Engine.NativeKeyWorld.Codes.OrderBy(code => code));
    }
}
