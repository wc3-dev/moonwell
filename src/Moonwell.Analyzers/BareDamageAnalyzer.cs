using System.Collections.Immutable;
using System.Linq;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Diagnostics;

namespace Moonwell.Analyzers;

/// <summary>
/// Names the fix for a bare <c>Damage(...)</c> in a unit class (MW0050), beside the compiler's CS1955: the declared field is
/// the name that binds there, and <c>Damage</c> the method is an extension, which C# finds only after a dot.
/// </summary>
[DiagnosticAnalyzer(LanguageNames.CSharp)]
public sealed class BareDamageAnalyzer : DiagnosticAnalyzer
{
    public override ImmutableArray<DiagnosticDescriptor> SupportedDiagnostics => Rules.BareDamages;

    public override void Initialize(AnalysisContext context)
    {
        // CSharp.lua compiles a map file that looks generated (Hud.g.cs, an <auto-generated> header) like any other.
        context.ConfigureGeneratedCodeAnalysis(GeneratedCodeAnalysisFlags.Analyze | GeneratedCodeAnalysisFlags.ReportDiagnostics);
        context.EnableConcurrentExecution();
        context.RegisterSyntaxNodeAction(Call, SyntaxKind.InvocationExpression);
    }

    private static void Call(SyntaxNodeAnalysisContext context)
    {
        var call = (InvocationExpressionSyntax)context.Node;
        if (call.Expression is not IdentifierNameSyntax { Identifier.ValueText: "Damage" } name)
        {
            return;
        }

        var bound = context.SemanticModel.GetSymbolInfo(name, context.CancellationToken);
        var symbols = bound.Symbol != null ? new[] { bound.Symbol } : bound.CandidateSymbols.ToArray();
        if (symbols.Any(symbol => symbol is IPropertySymbol { ContainingType: { } type } && IsUnit(type)))
        {
            context.ReportDiagnostic(Diagnostic.Create(Rules.BareDamage, call.GetLocation()));
        }
    }

    // A class that inherits Moonwell's Unit.
    private static bool IsUnit(INamedTypeSymbol type)
    {
        for (var parent = (INamedTypeSymbol?)type; parent != null; parent = parent.BaseType)
        {
            if (parent.Name == "Unit" && parent.ContainingNamespace is { Name: "Moonwell", ContainingNamespace.IsGlobalNamespace: true })
            {
                return true;
            }
        }

        return false;
    }
}
