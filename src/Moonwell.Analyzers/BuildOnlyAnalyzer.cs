using System;
using System.Collections.Immutable;
using System.ComponentModel;
using System.Linq;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Diagnostics;
using Microsoft.CodeAnalysis.Operations;

namespace Moonwell.Analyzers;

/// <summary>
/// Keeps a map from what only the code the build writes does. MW0045: a member Moonwell hides from the editor, which that
/// code calls and so has to be public. MW0046: new of a class whose objects the game has, whose constructor that code
/// needs. The namespace Moonwell.Generated is the build's, so it is left alone; a map's own file there would pass.
/// </summary>
[DiagnosticAnalyzer(LanguageNames.CSharp)]
public sealed class BuildOnlyAnalyzer : DiagnosticAnalyzer
{
    private const string GeneratedNamespace = "Moonwell.Generated";

    public override ImmutableArray<DiagnosticDescriptor> SupportedDiagnostics => Rules.BuildOnly;

    public override void Initialize(AnalysisContext context)
    {
        // CSharp.lua compiles a map file that looks generated (Hud.g.cs, an <auto-generated> header) like any other.
        context.ConfigureGeneratedCodeAnalysis(GeneratedCodeAnalysisFlags.Analyze | GeneratedCodeAnalysisFlags.ReportDiagnostics);
        context.EnableConcurrentExecution();
        context.RegisterOperationAction(Call, OperationKind.Invocation);
        context.RegisterOperationAction(Reference, OperationKind.MethodReference);
        context.RegisterOperationAction(Made, OperationKind.ObjectCreation, OperationKind.TypeParameterObjectCreation);
    }

    private static void Call(OperationAnalysisContext context)
    {
        Check(context, ((IInvocationOperation)context.Operation).TargetMethod);
    }

    private static void Reference(OperationAnalysisContext context)
    {
        Check(context, ((IMethodReferenceOperation)context.Operation).Method);
    }

    private static void Check(OperationAnalysisContext context, IMethodSymbol method)
    {
        if (IsMoonwell(method.ContainingAssembly) && IsHidden(method) && !InGenerated(context))
        {
            context.ReportDiagnostic(Diagnostic.Create(Rules.BuildOnlyMember, context.Operation.Syntax.GetLocation(), method.ContainingType.Name + "." + method.Name));
        }
    }

    private static void Made(OperationAnalysisContext context)
    {
        var made = context.Operation.Type;
        var kind = KindOf(made);
        if (kind != null && !InGenerated(context))
        {
            context.ReportDiagnostic(Diagnostic.Create(Rules.NewOfGameObject, context.Operation.Syntax.GetLocation(), context.Operation.Syntax.ToString(), Instead(kind, made!.Name)));
        }
    }

    /// <summary>The Moonwell class of game objects a type derives from, or that a type parameter is limited to; null for any other type.</summary>
    private static string? KindOf(ITypeSymbol? type)
    {
        if (type is ITypeParameterSymbol parameter)
        {
            return parameter.ConstraintTypes.Select(KindOf).FirstOrDefault(kind => kind != null);
        }

        for (var current = type; current != null; current = current.BaseType)
        {
            if (current.Name is "Unit" or "Item" or "Destructable" or "Ability" or "Doodad" or "Upgrade"
                && current.ContainingNamespace?.ToDisplayString() == "Moonwell" && IsMoonwell(current.ContainingAssembly))
            {
                return current.Name;
            }
        }

        return null;
    }

    /// <summary>What to write instead of new of a class of a kind.</summary>
    private static string Instead(string kind, string name)
    {
        switch (kind)
        {
            case "Unit":
                return "write Unit.Create<" + name + ">(player, x, y, scope) to make one in the game, or Unit.Default<" + name + ">() for its declared values";
            case "Item":
                return "write Item.Create<" + name + ">(x, y, scope) to make one in the game, or Item.Default<" + name + ">() for its declared values";
            case "Destructable":
                return "the game makes a destructable, and Moonwell gives it its class, so read its declared values on one in the game";
            case "Ability":
                return "write unit.AbilityOf<" + name + ">() for the object a unit has of it, which reads its declared values";
            default:
                return "a " + kind.ToLowerInvariant() + " class is data for the build, and the game gives no handle to one";
        }
    }

    private static bool IsHidden(IMethodSymbol method)
    {
        foreach (var attribute in method.OriginalDefinition.GetAttributes())
        {
            if (attribute.AttributeClass?.Name == nameof(EditorBrowsableAttribute) && attribute.ConstructorArguments.Length == 1
                && attribute.ConstructorArguments[0].Value is int state && state == (int)EditorBrowsableState.Never)
            {
                return true;
            }
        }

        return false;
    }

    private static bool InGenerated(OperationAnalysisContext context) =>
        context.ContainingSymbol.ContainingNamespace?.ToDisplayString() == GeneratedNamespace;

    private static bool IsMoonwell(IAssemblySymbol? assembly) =>
        assembly?.Name is { } name && (name == "Moonwell" || name.StartsWith("Moonwell.", StringComparison.Ordinal));
}
