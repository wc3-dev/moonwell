using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Diagnostics;

namespace Moonwell.Analyzers;

/// <summary>
/// The build's id checks in the editor: a declared object class with no <c>[ObjectId]</c>, a buff with no carrier id
/// (MW0013), and an id that is not four characters from ASCII's <c>!</c> to <c>~</c>, or has a comma (which splits a
/// list field that names the object), or whose first letter's case is wrong for a unit or a hero (MW0014).
/// A declared class is one the build makes an object of: not abstract or generic, and inheriting a standard object's
/// kind base (<c>StandardUnit</c> and the rest). Which ids are free, and which a standard object has, only the build
/// knows, so it still names a free one.
/// </summary>
[DiagnosticAnalyzer(LanguageNames.CSharp)]
public sealed class IdAnalyzer : DiagnosticAnalyzer
{
    private const string ObjectsNamespace = "Moonwell.Objects";

    private static readonly Dictionary<string, string> KindOfBase = new()
    {
        ["StandardUnit"] = "unit",
        ["StandardHero"] = "hero",
        ["StandardItem"] = "item",
        ["StandardDestructable"] = "destructable",
        ["StandardDoodad"] = "doodad",
        ["StandardAbility"] = "ability",
        ["StandardBuff"] = "buff",
        ["StandardUpgrade"] = "upgrade",
    };

    public override ImmutableArray<DiagnosticDescriptor> SupportedDiagnostics => Rules.Ids;

    public override void Initialize(AnalysisContext context)
    {
        // CSharp.lua compiles a map file that looks generated (Hud.g.cs, an <auto-generated> header) like any other.
        context.ConfigureGeneratedCodeAnalysis(GeneratedCodeAnalysisFlags.Analyze | GeneratedCodeAnalysisFlags.ReportDiagnostics);
        context.EnableConcurrentExecution();
        context.RegisterSymbolAction(Class, SymbolKind.NamedType);
    }

    // Read from the class's attributes, so a partial class's other parts and an id given as a constant count.
    private static void Class(SymbolAnalysisContext context)
    {
        var type = (INamedTypeSymbol)context.Symbol;
        if (type.TypeKind != TypeKind.Class || type.IsAbstract || type.IsGenericType || HasAttribute(type, "StandardAttribute")
            || type.Locations.FirstOrDefault(location => location.IsInSource) is not { } named)
        {
            return;
        }

        var kind = KindOf(type);
        if (kind == null)
        {
            return;
        }

        var objectId = Attribute(type, "ObjectIdAttribute");
        var replaces = Attribute(type, "ReplacesAttribute");
        var id = objectId?.ConstructorArguments.FirstOrDefault().Value as string;
        var carrier = objectId?.NamedArguments.FirstOrDefault(argument => argument.Key == "Carrier").Value.Value as string;

        if (id == null && replaces == null)
        {
            context.ReportDiagnostic(Diagnostic.Create(Rules.NoId, named, type.Name, MissingId(kind)));
        }
        else if (kind == "buff" && carrier == null)
        {
            var at = objectId ?? replaces!;
            var what = objectId != null && id != null
                ? "add Carrier = \"...\" to its [ObjectId]"
                : "add [ObjectId(Carrier = \"...\")] to it";
            context.ReportDiagnostic(Diagnostic.Create(Rules.NoId, at.ApplicationSyntaxReference?.GetSyntax(context.CancellationToken).GetLocation() ?? named, type.Name,
                $"no carrier id; {what}, the id of the hidden ability that shows the buff's icon"));
        }

        if (id != null)
        {
            CheckShape(context, type.Name, kind, id, Where(objectId!, null, context));
        }

        if (carrier != null)
        {
            CheckShape(context, type.Name, "ability", carrier, Where(objectId!, "Carrier", context));
        }
    }

    private static string MissingId(string kind)
    {
        switch (kind)
        {
            case "unit":
                return "no object id; add [ObjectId(\"...\")] with a unit's id, which starts with a lower-case letter";
            case "hero":
                return "no object id; add [ObjectId(\"...\")] with a hero's id, which starts with an upper-case letter";
            default:
                return "no object id; add [ObjectId(\"...\")] to it";
        }
    }

    private static void CheckShape(SymbolAnalysisContext context, string owner, string kind, string id, Location location)
    {
        string? why = null;
        if (id.Length != 4)
        {
            why = $"has the id \"{id}\", which is not four characters";
        }
        else if (id.IndexOf(',') >= 0)
        {
            why = $"has the id \"{id}\", with a comma, which splits a list field that names the object";
        }
        else if (id.Any(letter => letter < '!' || letter > '~'))
        {
            why = $"has the id \"{id}\", with a character that is not an ASCII letter, digit or sign";
        }
        else if (kind == "hero" && !IsUpper(id[0]))
        {
            why = $"is a hero, so its id {id} must start with an upper-case letter";
        }
        else if (kind == "unit" && IsUpper(id[0]))
        {
            why = $"is a unit, so its id {id} must not start with an upper-case letter: the game makes such a unit a hero";
        }

        if (why != null)
        {
            context.ReportDiagnostic(Diagnostic.Create(Rules.BadId, location, owner, why));
        }
    }

    private static bool IsUpper(char letter) => letter >= 'A' && letter <= 'Z';

    // The kind of the nearest kind base in the class's base chain: hero before unit, as StandardHero inherits StandardUnit.
    private static string? KindOf(INamedTypeSymbol type)
    {
        for (var at = type.BaseType; at != null; at = at.BaseType)
        {
            if (at.ContainingNamespace?.ToDisplayString() == ObjectsNamespace && KindOfBase.TryGetValue(at.Name, out var kind))
            {
                return kind;
            }
        }

        return null;
    }

    private static bool HasAttribute(INamedTypeSymbol type, string name)
    {
        return type.GetAttributes().Any(attribute => attribute.AttributeClass?.Name == name
            && attribute.AttributeClass.ContainingNamespace?.ToDisplayString() == ObjectsNamespace);
    }

    private static AttributeData? Attribute(INamedTypeSymbol type, string name)
    {
        return type.GetAttributes().FirstOrDefault(attribute => attribute.AttributeClass?.Name == name
            && attribute.AttributeClass.ContainingNamespace?.ToDisplayString() == ObjectsNamespace);
    }

    // Where an attribute gives a value: its id (the argument with no name, or id:), or a named one; else the attribute itself.
    private static Location Where(AttributeData attribute, string? named, SymbolAnalysisContext context)
    {
        if (attribute.ApplicationSyntaxReference?.GetSyntax(context.CancellationToken) is not AttributeSyntax syntax)
        {
            return Location.None;
        }

        var argument = syntax.ArgumentList?.Arguments.FirstOrDefault(argument => named == null
            ? argument.NameEquals == null
            : argument.NameEquals?.Name.Identifier.ValueText == named);
        return (argument?.Expression ?? (SyntaxNode)syntax).GetLocation();
    }
}
