using System.Globalization;
using System.Text;
using System.Text.Json;
using Microsoft.CodeAnalysis.CSharp;

namespace Moonwell.Build
{
    /// <summary>
    /// Writes <c>Data.g.cs</c> before the compile from the CSV and JSON files in the project's <c>data</c> folder (decision 259):
    /// the class <c>Moonwell.Data</c>, with a class for each file that object constructors and game code read
    /// (<c>Data.Abilities.Smite.Damage</c>, <c>Data.Waves.All</c>), so a wrong name is a compile error.
    /// </summary>
    /// <remarks>
    /// <para>
    /// A CSV file is a table: its first line names the columns, and each line after it is a <c>Row</c>, in <c>All</c> in the
    /// file's order. When the first column holds names, not numbers, each row is also a member named by it. A column is
    /// <c>int</c> when every value is a whole number (Moonwell.Json's rule, decision 178), else <c>float</c> when every value is a
    /// number, else <c>string</c>; a column with a <c>;</c> in a value is a list of them. <c>Damage:float</c>, <c>:int</c> or
    /// <c>:text</c> in the header gives the type. An empty value is 0, or the empty text or list.
    /// </para>
    /// <para>
    /// A JSON file is typed from its shape: an object is a static class of its keys, a list of objects a list of an <c>Item</c>
    /// class with every key its objects have, a whole number an <c>int</c> and other numbers <c>float</c>. A list at the top is <c>All</c>.
    /// </para>
    /// <para>Rows and items are made by constructor calls: an object initializer would be a local of the Lua's, which allows 200 in a function.</para>
    /// </remarks>
    public static class DataWriter
    {
        /// <summary>The file's name in the generated folder, which the map's project compiles.</summary>
        public const string FileName = "Data.g.cs";

        /// <summary>Writes <c>Data.g.cs</c> into the generated folder, or deletes one left from an earlier build when <c>data</c> holds no CSV or JSON file.</summary>
        /// <param name="project">The map project.</param>
        /// <exception cref="BuildException">A file cannot be read or made into C#; the message names it and, for a CSV, its line.</exception>
        public static void Write(MapProject project)
        {
            var path = Path.Combine(project.GeneratedFolder, FileName);
            var files = Directory.Exists(project.DataFolder)
                ? Directory.GetFiles(project.DataFolder)
                    .Where(file => Path.GetExtension(file).ToLowerInvariant() is ".csv" or ".json")
                    .OrderBy(file => file, StringComparer.OrdinalIgnoreCase)
                    .ToList()
                : new List<string>();
            if (files.Count == 0)
            {
                if (File.Exists(path))
                {
                    File.Delete(path);
                }

                return;
            }

            var text = new StringBuilder();
            text.Append("// Generated by Moonwell's build from the files in data\\. Do not edit; every build writes it anew.\n");
            text.Append("#nullable disable\n");
            text.Append("namespace Moonwell\n{\n");
            text.Append("    /// <summary>The CSV and JSON files in the project's data folder, a class for each.</summary>\n");
            text.Append("    public static class Data\n    {\n");
            var made = new Dictionary<string, string>(StringComparer.Ordinal);
            var first = true;
            foreach (var file in files)
            {
                var shown = "data\\" + Path.GetFileName(file);
                var name = Name(Path.GetFileNameWithoutExtension(file), shown, "its file name");
                if (made.TryGetValue(name, out var other))
                {
                    throw new BuildException($"{other} and {shown} both make Data.{name}; rename one");
                }

                made[name] = shown;
                text.Append(first ? string.Empty : "\n");
                first = false;
                var lines = new Lines("        ");
                if (Path.GetExtension(file).Equals(".csv", StringComparison.OrdinalIgnoreCase))
                {
                    Csv(lines, name, shown, ReadText(file, shown));
                }
                else
                {
                    Json(lines, name, shown, ReadText(file, shown));
                }

                text.Append(lines);
            }

            text.Append("    }\n}\n");
            Directory.CreateDirectory(project.GeneratedFolder);
            File.WriteAllText(path, text.ToString());
        }

        private static string ReadText(string file, string shown)
        {
            try
            {
                return File.ReadAllText(file);
            }
            catch (Exception failure) when (failure is IOException or UnauthorizedAccessException)
            {
                throw new BuildException($"cannot read {shown}: {failure.Message}");
            }
        }

        // A CSV table: a static class with the Row class, a member for each named row and All.
        private static void Csv(Lines lines, string name, string shown, string text)
        {
            var table = CsvTable.Parse(text, shown);
            if (table.Count == 0)
            {
                throw new BuildException($"{shown} has no header line");
            }

            var header = table[0];
            var columns = new List<Column>();
            var names = new HashSet<string>(StringComparer.Ordinal) { "Row" };
            foreach (var cell in header.Cells)
            {
                var colon = cell.LastIndexOf(':');
                var title = colon < 0 ? cell : cell.Substring(0, colon);
                var forced = colon < 0 ? null : cell.Substring(colon + 1).Trim();
                if (forced is not (null or "int" or "float" or "text"))
                {
                    throw new BuildException($"{shown}:{header.Line}: the column {cell} asks for the type {forced}; use int, float or text");
                }

                var field = Name(title, $"{shown}:{header.Line}", "the column " + cell);
                if (!names.Add(field))
                {
                    throw new BuildException($"{shown}:{header.Line}: two columns make the name {field}" + (field == "Row" ? ", which the rows' class has" : string.Empty));
                }

                columns.Add(new Column(field, forced));
            }

            var rows = table.Skip(1).ToList();
            foreach (var row in rows.Where(row => row.Cells.Count > columns.Count))
            {
                throw new BuildException($"{shown}:{row.Line}: {row.Cells.Count} values, and the header names {columns.Count} columns");
            }

            var shapes = columns.Select((column, at) => ColumnShape(column, rows.Select(row => at < row.Cells.Count ? row.Cells[at] : string.Empty), shown)).ToList();
            lines.Add($"/// <summary>The rows of {shown}.</summary>");
            lines.Open($"public static class {name}");
            lines.Add("/// <summary>A row of the table.</summary>");
            lines.Open("public sealed class Row");
            for (var at = 0; at < columns.Count; at++)
            {
                lines.Add($"/// <summary>The column {columns[at].Name}.</summary>");
                lines.Add($"public readonly {TypeOf(shapes[at], columns[at].Name)} {columns[at].Name};");
            }

            Constructor(lines, "Row", columns.Select((column, at) => (column.Name, TypeOf(shapes[at], column.Name))).ToList());
            lines.Close();

            var calls = rows.Select(row => "new Row(" + string.Join(", ", columns.Select((column, at) => Literal(Cell(at < row.Cells.Count ? row.Cells[at] : string.Empty, shapes[at], column.Forced), shapes[at], column.Name))) + ")").ToList();
            if (shapes.Count > 0 && shapes[0] is Scalar { Kind: ScalarKind.Text })
            {
                var rowNames = new HashSet<string>(StringComparer.Ordinal) { "All", "Row", name };
                for (var at = 0; at < rows.Count; at++)
                {
                    var rowName = Name(rows[at].Cells.Count > 0 ? rows[at].Cells[0] : string.Empty, $"{shown}:{rows[at].Line}", "the row's name");
                    if (!rowNames.Add(rowName))
                    {
                        throw new BuildException($"{shown}:{rows[at].Line}: the row's name {rowName} is taken" + (rowName is "All" or "Row" ? " by Moonwell" : rowName == name ? " by the file's class" : " by an earlier row"));
                    }

                    lines.Add($"public static readonly Row {rowName} = {calls[at]};");
                    calls[at] = rowName;
                }
            }

            lines.Add("/// <summary>Every row, in the file's order.</summary>");
            lines.Add("public static readonly Row[] All = new Row[] { " + string.Join(", ", calls) + " };");
            lines.Close();
        }

        // The shape of a column: a list when a value holds a ;, of whole numbers, numbers or text by what every value is.
        private static Shape ColumnShape(Column column, IEnumerable<string> cells, string shown)
        {
            var values = cells.ToList();
            var list = values.Any(value => value.Contains(';'));
            var parts = list ? values.SelectMany(value => Parts(value)) : values.Where(value => value.Trim().Length > 0);
            var kind = column.Forced switch
            {
                "int" => ScalarKind.Int,
                "float" => ScalarKind.Float,
                "text" => ScalarKind.Text,
                _ => parts.All(part => IsWhole(part)) ? ScalarKind.Int : parts.All(part => IsNumber(part)) ? ScalarKind.Float : ScalarKind.Text,
            };
            if (kind == ScalarKind.Int && parts.FirstOrDefault(part => !IsWhole(part)) is { } notWhole)
            {
                throw new BuildException($"{shown}: the column {column.Name} is int, and '{notWhole}' is not a whole number");
            }

            if (kind == ScalarKind.Float && parts.FirstOrDefault(part => !IsNumber(part)) is { } notNumber)
            {
                throw new BuildException($"{shown}: the column {column.Name} is float, and '{notNumber}' is not a number");
            }

            Shape scalar = new Scalar(kind);
            return list ? new ListShape(scalar) : scalar;
        }

        private static object? Cell(string cell, Shape shape, string? forced)
        {
            return shape is ListShape list
                ? Parts(cell).Select(part => Cell(part, list.Element!, forced)).ToList()
                : ((Scalar)shape).Kind switch
                {
                    ScalarKind.Int => cell.Trim().Length == 0 ? 0L : long.Parse(cell.Trim(), NumberStyles.Integer, CultureInfo.InvariantCulture),
                    ScalarKind.Float => cell.Trim().Length == 0 ? 0.0 : double.Parse(cell.Trim(), NumberStyles.Float, CultureInfo.InvariantCulture),
                    _ => cell,
                };
        }

        private static IEnumerable<string> Parts(string value)
        {
            return value.Trim().Length == 0 ? Enumerable.Empty<string>() : value.Split(';').Select(part => part.Trim());
        }

        private static bool IsNumber(string text)
        {
            return double.TryParse(text.Trim(), NumberStyles.Float, CultureInfo.InvariantCulture, out var number) && double.IsFinite(number);
        }

        // Whole and in an int's range, as Moonwell.Json reads a number.
        private static bool IsWhole(string text)
        {
            return double.TryParse(text.Trim(), NumberStyles.Float, CultureInfo.InvariantCulture, out var number) && Whole(number);
        }

        private static bool Whole(double number)
        {
            return Math.Floor(number) == number && number >= int.MinValue && number <= int.MaxValue;
        }

        // A JSON file: an object as a static class of its keys, a list as All.
        private static void Json(Lines lines, string name, string shown, string text)
        {
            object? root;
            try
            {
                using var document = JsonDocument.Parse(text, new JsonDocumentOptions { AllowTrailingCommas = true, CommentHandling = JsonCommentHandling.Skip });
                root = Value(document.RootElement);
            }
            catch (JsonException failure)
            {
                throw new BuildException($"{shown} is not JSON: {failure.Message}");
            }

            lines.Add($"/// <summary>What {shown} holds.</summary>");
            if (root is Fields fields)
            {
                StaticClass(lines, name, fields, shown);
                return;
            }

            lines.Open($"public static class {name}");
            StaticMember(lines, "All", root, shown, new HashSet<string>(StringComparer.Ordinal) { name });
            lines.Close();
        }

        private static void StaticClass(Lines lines, string name, Fields fields, string shown)
        {
            lines.Open($"public static class {name}");
            var names = new HashSet<string>(StringComparer.Ordinal) { name };
            foreach (var (key, value) in fields)
            {
                var member = Name(key, shown, "the key " + key);
                if (!names.Add(member))
                {
                    throw new BuildException($"{shown}: the key {key} makes the name {member}, which " + (member == name ? "its class has" : "another key makes"));
                }

                if (value is Fields inner)
                {
                    StaticClass(lines, member, inner, shown);
                }
                else
                {
                    StaticMember(lines, member, value, shown, names);
                }
            }

            lines.Close();
        }

        // A static field: its value, with the classes of the objects in it beside it.
        private static void StaticMember(Lines lines, string member, object? value, string shown, HashSet<string> names)
        {
            var shape = ShapeOf(value, shown, member);
            foreach (var type in Classes(shape, member))
            {
                if (!names.Add(type.Name))
                {
                    throw new BuildException($"{shown}: the key {member} needs the class {type.Name}, which another key makes");
                }

                InstanceClass(lines, type.Name, type.Shape);
            }

            lines.Add($"public static readonly {TypeOf(shape, member)} {member} = {Literal(value, shape, member)};");
        }

        // An object inside a list: fields, a constructor, and the classes of the objects in its fields.
        private static void InstanceClass(Lines lines, string name, ObjectShape shape)
        {
            lines.Open($"public sealed class {name}");
            foreach (var field in shape.Fields)
            {
                lines.Add($"public readonly {TypeOf(field.Shape, field.Name)} {field.Name};");
            }

            Constructor(lines, name, shape.Fields.Select(field => (field.Name, TypeOf(field.Shape, field.Name))).ToList());
            foreach (var field in shape.Fields)
            {
                foreach (var type in Classes(field.Shape, field.Name))
                {
                    InstanceClass(lines, type.Name, type.Shape);
                }
            }

            lines.Close();
        }

        // The object shape in a field's shape, or in its list's, named for the field: Steps holds StepsItem.
        private static IEnumerable<(string Name, ObjectShape Shape)> Classes(Shape? shape, string field)
        {
            while (shape is ListShape list)
            {
                shape = list.Element;
            }

            return shape is ObjectShape objectShape ? new[] { (ItemName(field), objectShape) } : Enumerable.Empty<(string, ObjectShape)>();
        }

        private static string ItemName(string field)
        {
            return field == "All" ? "Item" : field + "Item";
        }

        private static void Constructor(Lines lines, string name, IReadOnlyList<(string Name, string Type)> fields)
        {
            lines.Add($"/// <summary>Holds the values, in the order of the fields.</summary>");
            lines.Open($"public {name}(" + string.Join(", ", fields.Select((field, at) => $"{field.Type} p{at}")) + ")");
            for (var at = 0; at < fields.Count; at++)
            {
                lines.Add($"{fields[at].Name} = p{at};");
            }

            lines.Close();
        }

        // A JSON value as long, double, bool, string, a list, Fields or null.
        private static object? Value(JsonElement element)
        {
            switch (element.ValueKind)
            {
                case JsonValueKind.Object:
                    var fields = new Fields();
                    foreach (var property in element.EnumerateObject())
                    {
                        fields.Add((property.Name, Value(property.Value)));
                    }

                    return fields;
                case JsonValueKind.Array:
                    return element.EnumerateArray().Select(Value).ToList();
                case JsonValueKind.Number:
                    var number = element.GetDouble();
                    return Whole(number) ? (object)(long)number : number;
                case JsonValueKind.String:
                    return element.GetString();
                case JsonValueKind.True:
                    return true;
                case JsonValueKind.False:
                    return false;
                default:
                    return null;
            }
        }

        // The shape of a JSON value: what its lists' items and its objects' keys hold, merged; null for a null or an empty list's items.
        private static Shape? ShapeOf(object? value, string shown, string where)
        {
            switch (value)
            {
                case long:
                    return new Scalar(ScalarKind.Int);
                case double:
                    return new Scalar(ScalarKind.Float);
                case bool:
                    return new Scalar(ScalarKind.Bool);
                case string:
                    return new Scalar(ScalarKind.Text);
                case List<object?> items:
                    return new ListShape(items.Aggregate<object?, Shape?>(null, (merged, item) => Merge(merged, ShapeOf(item, shown, where), shown, where)));
                case Fields fields:
                    var shape = new ObjectShape(new List<FieldShape>());
                    foreach (var (key, inner) in fields)
                    {
                        var name = Name(key, shown, "the key " + key);
                        if (shape.Fields.Any(field => field.Name == name))
                        {
                            throw new BuildException($"{shown}: two keys of an object in {where} make the name {name}");
                        }

                        shape.Fields.Add(new FieldShape(name, key, ShapeOf(inner, shown, where + "." + name)));
                    }

                    return shape;
                default:
                    return null;
            }
        }

        private static Shape? Merge(Shape? a, Shape? b, string shown, string where)
        {
            if (a == null || b == null)
            {
                return a ?? b;
            }

            switch (a, b)
            {
                case (Scalar x, Scalar y) when x.Kind == y.Kind:
                    return x;
                case (Scalar x, Scalar y) when x.Kind is ScalarKind.Int or ScalarKind.Float && y.Kind is ScalarKind.Int or ScalarKind.Float:
                    return new Scalar(ScalarKind.Float);
                case (ListShape x, ListShape y):
                    return new ListShape(Merge(x.Element, y.Element, shown, where));
                case (ObjectShape x, ObjectShape y):
                    var fields = x.Fields.Select(field => field with { }).ToList();
                    foreach (var field in y.Fields)
                    {
                        var at = fields.FindIndex(one => one.Name == field.Name);
                        if (at < 0)
                        {
                            fields.Add(field);
                        }
                        else
                        {
                            fields[at] = fields[at] with { Shape = Merge(fields[at].Shape, field.Shape, shown, where + "." + field.Name) };
                        }
                    }

                    return new ObjectShape(fields);
                default:
                    throw new BuildException($"{shown}: {where} holds {Describe(a)} in one place and {Describe(b)} in another; a list's items share one shape");
            }
        }

        private static string Describe(Shape shape)
        {
            return shape switch
            {
                Scalar { Kind: ScalarKind.Bool } => "true or false",
                Scalar { Kind: ScalarKind.Text } => "text",
                Scalar => "a number",
                ListShape => "a list",
                _ => "an object",
            };
        }

        private static string TypeOf(Shape? shape, string field)
        {
            return shape switch
            {
                Scalar { Kind: ScalarKind.Int } => "int",
                Scalar { Kind: ScalarKind.Float } => "float",
                Scalar { Kind: ScalarKind.Bool } => "bool",
                ListShape list => TypeOf(list.Element, field) + "[]",
                ObjectShape => ItemName(field),
                _ => "string",
            };
        }

        private static string Literal(object? value, Shape? shape, string field)
        {
            switch (shape)
            {
                case Scalar { Kind: ScalarKind.Int }:
                    return Convert.ToInt64(value ?? 0L, CultureInfo.InvariantCulture).ToString(CultureInfo.InvariantCulture);
                case Scalar { Kind: ScalarKind.Float }:
                    return ((float)Convert.ToDouble(value ?? 0.0, CultureInfo.InvariantCulture)).ToString("R", CultureInfo.InvariantCulture) + "f";
                case Scalar { Kind: ScalarKind.Bool }:
                    return value is true ? "true" : "false";
                case ListShape list:
                    var items = value as List<object?> ?? new List<object?>();
                    return items.Count == 0
                        ? $"new {TypeOf(list.Element, field)}[0]"
                        : $"new {TypeOf(list, field)} {{ " + string.Join(", ", items.Select(item => Literal(item, list.Element, field))) + " }";
                case ObjectShape objectShape:
                    if (value is not Fields fields)
                    {
                        return "null";
                    }

                    return $"new {ItemName(field)}(" + string.Join(", ", objectShape.Fields.Select(one => Literal(fields.FirstOrDefault(pair => pair.Key == one.Key).Value, one.Shape, one.Name))) + ")";
                default:
                    return SymbolDisplay.FormatLiteral(value as string ?? string.Empty, true);
            }
        }

        // A C# name from a file name, column, key or row name: each word with a capital, other characters left out ("hit points" is HitPoints).
        internal static string Name(string text, string where, string what)
        {
            var name = new StringBuilder();
            var capital = true;
            foreach (var letter in text.Trim())
            {
                if (char.IsLetterOrDigit(letter) && !char.IsAscii(letter))
                {
                    throw new BuildException($"{where}: {what} ('{text}') has the letter {letter}, and the map's Lua takes names of the letters a to z, digits and _ only");
                }

                if (char.IsAsciiLetterOrDigit(letter) || letter == '_')
                {
                    name.Append(capital ? char.ToUpperInvariant(letter) : letter);
                    capital = false;
                }
                else
                {
                    capital = true;
                }
            }

            if (name.Length == 0 || char.IsDigit(name[0]) || SyntaxFacts.GetKeywordKind(name.ToString()) != SyntaxKind.None)
            {
                throw new BuildException($"{where}: {what} makes no C# name ('{text}'); start it with a letter");
            }

            return name.ToString();
        }

        private enum ScalarKind
        {
            Int,
            Float,
            Bool,
            Text,
        }

        private abstract record Shape;

        private sealed record Scalar(ScalarKind Kind) : Shape;

        private sealed record ListShape(Shape? Element) : Shape;

        private sealed record ObjectShape(List<FieldShape> Fields) : Shape;

        private sealed record FieldShape(string Name, string Key, Shape? Shape);

        private sealed record Column(string Name, string? Forced);

        /// <summary>A JSON object's keys and values, in order.</summary>
        private sealed class Fields : List<(string Key, object? Value)>
        {
        }

        /// <summary>Indented lines of C#.</summary>
        private sealed class Lines
        {
            private readonly StringBuilder text = new StringBuilder();
            private string indent;

            public Lines(string indent)
            {
                this.indent = indent;
            }

            public void Add(string line)
            {
                text.Append(indent).Append(line).Append('\n');
            }

            public void Open(string line)
            {
                Add(line);
                Add("{");
                indent += "    ";
            }

            public void Close()
            {
                indent = indent.Substring(4);
                Add("}");
            }

            public override string ToString()
            {
                return text.ToString();
            }
        }

        /// <summary>The lines of a CSV file, each with its cells; a quoted cell may hold commas, quotes ("") and line breaks.</summary>
        internal static class CsvTable
        {
            public static List<(int Line, List<string> Cells)> Parse(string text, string shown)
            {
                var rows = new List<(int Line, List<string> Cells)>();
                var cells = new List<string>();
                var cell = new StringBuilder();
                var line = 1;
                var start = 1;
                var quoted = false;
                var any = false;
                for (var at = 0; at < text.Length; at++)
                {
                    var letter = text[at];
                    if (quoted)
                    {
                        if (letter == '"' && at + 1 < text.Length && text[at + 1] == '"')
                        {
                            cell.Append('"');
                            at++;
                        }
                        else if (letter == '"')
                        {
                            quoted = false;
                        }
                        else
                        {
                            line += letter == '\n' ? 1 : 0;
                            cell.Append(letter);
                        }
                    }
                    else if (letter == '"' && cell.Length == 0)
                    {
                        quoted = true;
                        any = true;
                    }
                    else if (letter == ',')
                    {
                        cells.Add(cell.ToString());
                        cell.Clear();
                        any = true;
                    }
                    else if (letter == '\n' || letter == '\r')
                    {
                        if (letter == '\r' && at + 1 < text.Length && text[at + 1] == '\n')
                        {
                            at++;
                        }

                        End();
                        line++;
                        start = line;
                    }
                    else
                    {
                        cell.Append(letter);
                        any = true;
                    }
                }

                if (quoted)
                {
                    throw new BuildException($"{shown}:{start}: a quoted value has no closing quote");
                }

                End();
                return rows;

                void End()
                {
                    if (any || cell.Length > 0)
                    {
                        cells.Add(cell.ToString());
                        rows.Add((start, cells));
                    }

                    cells = new List<string>();
                    cell.Clear();
                    any = false;
                }
            }
        }
    }
