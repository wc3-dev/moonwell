using System.Globalization;

namespace Moonwell.Build
{
    /// <summary>
    /// Writes <c>HeroBonus.g.cs</c>, which gives the map's assembly the hero bonus the build read, so that Moonwell.Simulation's
    /// <c>Start(map)</c> reads a hero's life and mana as the build does. On .NET only; the Lua leaves it out.
    /// </summary>
    public static class HeroBonusWriter
    {
        /// <summary>The file's name in the generated folder.</summary>
        public const string FileName = "HeroBonus.g.cs";

        /// <summary>Writes the file into the project's generated folder.</summary>
        /// <param name="project">The map project.</param>
        /// <param name="bonus">The bonus the build read.</param>
        public static void Write(MapProject project, HeroBonus bonus)
        {
            var text = "// Generated by Moonwell's build from the map's gameplay constants. Do not edit; every build writes it anew.\n"
                + "#if !MOONWELL_LUA\n"
                + Line("Moonwell.LifePerStrength", bonus.LifePerStrength)
                + Line("Moonwell.ManaPerIntelligence", bonus.ManaPerIntelligence)
                + "#endif\n";
            Directory.CreateDirectory(project.GeneratedFolder);
            File.WriteAllText(Path.Combine(project.GeneratedFolder, FileName), text);
        }

        /// <summary>Deletes the file an earlier build left, for a map that no longer uses Moonwell.Objects.</summary>
        /// <param name="project">The map project.</param>
        public static void Delete(MapProject project)
        {
            var path = Path.Combine(project.GeneratedFolder, FileName);
            if (File.Exists(path))
            {
                File.Delete(path);
            }
        }

        private static string Line(string key, float value)
        {
            return $"[assembly: global::System.Reflection.AssemblyMetadata(\"{key}\", \"{value.ToString("R", CultureInfo.InvariantCulture)}\")]\n";
        }
    }
}
