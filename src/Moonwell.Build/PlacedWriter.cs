using System.Globalization;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Moonwell.GameData;
using Moonwell.MapFiles;
using War3Net.Build.Extensions;
using War3Net.Build.Widget;
using War3Net.Common.Extensions;

namespace Moonwell.Build
{
    /// <summary>
    /// Writes <c>Placed.g.cs</c> before the compile, from the map's files only: the class <c>Moonwell.Placed</c>, with a member for
    /// each unit, item, destructable (but the trees), region, camera and sound an editor placed in the map, named as World Editor
    /// names its variables without <c>gg_</c>. A unit, item or destructable whose type one class of the map's own gives in its
    /// <c>[ObjectId]</c> is typed as that class; the others are <c>Unit</c>, <c>Item</c> and <c>Destructable</c>. Also the table
    /// of placed destructables the runtime finds them by, and the names the build checks literals against.
    /// </summary>
    public static class PlacedWriter
    {
        /// <summary>The file's name in the generated folder, which the map's project compiles.</summary>
        public const string FileName = "Placed.g.cs";

        private const string TypesResource = "Moonwell.Build.Data.Destructables.txt";

        private const War3Net.Build.MapFiles PlacedFiles = War3Net.Build.MapFiles.Units | War3Net.Build.MapFiles.Doodads | War3Net.Build.MapFiles.Regions | War3Net.Build.MapFiles.Cameras | War3Net.Build.MapFiles.Sounds;

        /// <summary>Reads the map's placed things from its folder; an empty map when it has none.</summary>
        /// <param name="project">The map project.</param>
        /// <exception cref="BuildException">A file of the map's placed things cannot be read.</exception>
        public static War3Net.Build.Map Read(MapProject project)
        {
            if (!Directory.Exists(project.MapFolder))
            {
                return new War3Net.Build.Map();
            }

            try
            {
                return War3Net.Build.Map.Open(project.MapFolder, PlacedFiles);
            }
            catch (Exception failure) when (failure is not BuildException)
            {
                throw new BuildException($@"cannot read the World Editor map in map\: {failure.Message}");
            }
        }

        /// <summary>Writes <c>Placed.g.cs</c> into the project's generated folder.</summary>
        /// <param name="project">The map project.</param>
        /// <param name="map">The map's placed things, from <see cref="Read"/>.</param>
        /// <param name="release">Whether the build is a release build, whose symbols the classes are read with.</param>
        /// <returns>The path of the written file.</returns>
        public static string Write(MapProject project, War3Net.Build.Map map, bool release)
        {
            var classes = ClassesById(project, release);
            var trees = Trees(project);
            var text = new StringBuilder();
            text.Append("// Generated by Moonwell's build from the map's placed things. Do not edit; every build writes it anew.\n");
            text.Append("#nullable enable\n");
            text.Append("namespace Moonwell\n{\n");
            text.Append("    /// <summary>What an editor placed in the map, named as World Editor names its variables without gg_.</summary>\n");
            text.Append("    public static class Placed\n    {\n");

            Open(text, "Units", "The placed units: null once one has left the game.");
            var names = new HashSet<string>(StringComparer.Ordinal) { "Units" };
            foreach (var unit in Units(map))
            {
                var name = UnitName(unit);
                Lookup(text, names, name, Describe(unit.TypeId, unit.Position.X, unit.Position.Y), "Unit", classes, unit.TypeId);
            }

            Close(text);
            Open(text, "Items", "The placed items: null once one has left the game.");
            names = new HashSet<string>(StringComparer.Ordinal) { "Items" };
            foreach (var item in Items(map))
            {
                Lookup(text, names, UnitName(item), Describe(item.TypeId, item.Position.X, item.Position.Y), "Item", classes, item.TypeId);
            }

            Close(text);
            Open(text, "Destructables", "The placed destructables but the trees, which Destructable.Named finds: null once one is gone.");
            names = new HashSet<string>(StringComparer.Ordinal) { "Destructables" };
            foreach (var placed in Destructables(map, trees))
            {
                if (!placed.Tree)
                {
                    Lookup(text, names, placed.Name, Describe(placed.Doodad.TypeId, placed.Doodad.Position.X, placed.Doodad.Position.Y), "Destructable", classes, placed.Doodad.TypeId);
                }
            }

            Close(text);
            Open(text, "Regions", "The placed regions.");
            names = new HashSet<string>(StringComparer.Ordinal) { "Regions" };
            foreach (var region in map.Regions?.Regions ?? new List<War3Net.Build.Environment.Region>())
            {
                var member = Member(names, region.Name);
                text.Append($"            /// <summary>{Escape(region.Name)}.</summary>\n");
                text.Append($"            public static global::Moonwell.PlacedRegion {member} => new global::Moonwell.PlacedRegion({Quoted(region.Name)}, {Real(region.Left)}, {Real(region.Bottom)}, {Real(region.Right)}, {Real(region.Top)});\n");
            }

            Close(text);
            Open(text, "Cameras", "The placed cameras.");
            names = new HashSet<string>(StringComparer.Ordinal) { "Cameras" };
            foreach (var camera in map.Cameras?.Cameras ?? new List<War3Net.Build.Environment.Camera>())
            {
                var member = Member(names, camera.Name);
                text.Append($"            /// <summary>{Escape(camera.Name)}.</summary>\n");
                text.Append($"            public static global::Moonwell.PlacedCamera {member} => new global::Moonwell.PlacedCamera({Quoted(camera.Name)});\n");
            }

            Close(text);
            Open(text, "Sounds", "The sounds of the Sound Editor.");
            names = new HashSet<string>(StringComparer.Ordinal) { "Sounds" };
            foreach (var name in SoundNames(map))
            {
                var member = Member(names, name);
                text.Append($"            /// <summary>{Escape(name)}.</summary>\n");
                text.Append($"            public static global::Moonwell.PlacedSound? {member} => global::Moonwell.PlacedSound.Named({Quoted(name)});\n");
            }

            Close(text);
            text.Append("    }\n}\n");

            Directory.CreateDirectory(project.GeneratedFolder);
            var path = Path.Combine(project.GeneratedFolder, FileName);
            File.WriteAllText(path, text.ToString());
            return path;
        }

        /// <summary>The names <c>Unit.Named</c> takes: each placed unit's, <c>hfoo_0001</c>.</summary>
        public static IReadOnlyList<string> UnitNames(War3Net.Build.Map map) => Units(map).Select(UnitName).ToList();

        /// <summary>The names <c>Item.Named</c> takes: each placed item's, <c>ratc_0005</c>.</summary>
        public static IReadOnlyList<string> ItemNames(War3Net.Build.Map map) => Items(map).Select(UnitName).ToList();

        /// <summary>The names <c>Destructable.Named</c> takes: each placed destructable's, trees among them, <c>LTlt_0012</c>.</summary>
        public static IReadOnlyList<string> DestructableNames(MapProject project, War3Net.Build.Map map) => Destructables(map, Trees(project)).Select(placed => placed.Name).ToList();

        /// <summary>The names <c>PlacedSound.Named</c> takes: each sound's name without <c>gg_snd_</c>.</summary>
        public static IReadOnlyList<string> SoundNames(War3Net.Build.Map map)
        {
            const string Prefix = "gg_snd_";
            return (map.Sounds?.Sounds ?? new List<War3Net.Build.Audio.Sound>())
                .Select(sound => sound.Name.StartsWith(Prefix, StringComparison.Ordinal) ? sound.Name.Substring(Prefix.Length) : sound.Name)
                .ToList();
        }

        /// <summary>
        /// The Lua table <c>MoonwellPlacedDestructables = { [name] = { typeId, x, y } }</c> the runtime finds a placed destructable by,
        /// its type id in the game's order, as FourCC gives it and not as war3map.doo stores it,
        /// for a map whose code names <c>Destructable.Named</c> (every one) or <c>Placed.Destructables</c> (all but the trees); empty
        /// for any other map, which needs none.
        /// </summary>
        /// <param name="project">The map project, whose source says which it names.</param>
        /// <param name="map">The opened map.</param>
        public static string DestructableTable(MapProject project, War3Net.Build.Map map)
        {
            var named = Names(project, "Destructable.Named");
            if (!named && !Names(project, "Placed.Destructables"))
            {
                return string.Empty;
            }

            var text = new StringBuilder("MoonwellPlacedDestructables = {\n");
            foreach (var placed in Destructables(map, Trees(project)).Where(placed => named || !placed.Tree))
            {
                text.Append($"[{Quoted(placed.Name)}] = {{ {ObjectLua.FourCC(placed.Doodad.TypeId.ToRawcode())}, {LuaReal(placed.Doodad.Position.X)}, {LuaReal(placed.Doodad.Position.Y)} }},\n");
            }

            return text.Append("}\n").ToString();
        }

        private static IEnumerable<UnitData> Units(War3Net.Build.Map map) =>
            (map.Units?.Units ?? new List<UnitData>()).Where(unit => unit.IsUnit() && !unit.IsPlayerStartLocation());

        private static IEnumerable<UnitData> Items(War3Net.Build.Map map) =>
            (map.Units?.Units ?? new List<UnitData>()).Where(item => item.IsItem() && !item.IsPlayerStartLocation());

        private static string UnitName(UnitData unit) => $"{unit.TypeId.ToRawcode()}_{unit.CreationNumber:D4}";

        // The destructables of war3map.doo, by their name, and whether each is a tree; the doodads beside them are left out.
        private static IEnumerable<(string Name, DoodadData Doodad, bool Tree)> Destructables(War3Net.Build.Map map, IReadOnlyDictionary<int, bool> trees)
        {
            foreach (var doodad in map.Doodads?.Doodads ?? new List<DoodadData>())
            {
                if (trees.TryGetValue(doodad.TypeId, out var tree))
                {
                    yield return ($"{doodad.TypeId.ToRawcode()}_{doodad.CreationNumber:D4}", doodad, tree);
                }
            }
        }

        // The destructable types by id, and whether each is a tree: the game's (Data/Destructables.txt), then the map's own types
        // of war3map.w3b, which take their base's. shortcut: a map type whose own "Targeted As" adds or drops tree is not seen; read
        // its btar here if that is ever wanted.
        private static Dictionary<int, bool> Trees(MapProject project)
        {
            var trees = new Dictionary<int, bool>();
            using (var stream = typeof(PlacedWriter).Assembly.GetManifestResourceStream(TypesResource)
                ?? throw new InvalidOperationException(TypesResource + " is not embedded"))
            using (var reader = new StreamReader(stream))
            {
                string? line;
                while ((line = reader.ReadLine()) != null)
                {
                    if (line.Length >= 4 && line[0] != '#')
                    {
                        trees[line.Substring(0, 4).FromRawcode()] = line.EndsWith(" tree", StringComparison.Ordinal);
                    }
                }
            }

            foreach (var name in new[] { Kinds.MainName(Kind.Destructable), Kinds.SkinName(Kind.Destructable) })
            {
                var table = SourceObjectFile.Read(Path.Combine(project.MapFolder, name), Kind.Destructable);
                foreach (var entry in table.Entries)
                {
                    if (entry.BaseId.Length == 4 && trees.TryGetValue(entry.BaseId.FromRawcode(), out var tree))
                    {
                        trees[SourceObjectFile.IdOf(entry).FromRawcode()] = tree;
                    }
                }
            }

            return trees;
        }

        // The classes of the map's own source by the id their [ObjectId] gives, read from the syntax only, as the classes must be
        // known before the compile. An id more than one class gives (each of another kind) is left out, so its member is untyped.
        private static Dictionary<string, string> ClassesById(MapProject project, bool release)
        {
            var found = new Dictionary<string, List<string>>(StringComparer.Ordinal);
            var options = CSharpParseOptions.Default.WithLanguageVersion(LanguageVersion.Latest).WithPreprocessorSymbols("TRACE", release ? "RELEASE" : "DEBUG");
            foreach (var path in CompiledFiles.Sources(project, project.BuildFolder))
            {
                var tree = CSharpSyntaxTree.ParseText(CompiledFiles.ReadSource(path), options);
                foreach (var declared in tree.GetRoot().DescendantNodes().OfType<ClassDeclarationSyntax>())
                {
                    if (declared.TypeParameterList != null || declared.Modifiers.Any(SyntaxKind.AbstractKeyword) || IdOf(declared) is not { } id)
                    {
                        continue;
                    }

                    if (!found.TryGetValue(id, out var list))
                    {
                        found[id] = list = new List<string>();
                    }

                    list.Add(FullName(declared));
                }
            }

            return found.Where(entry => entry.Value.Count == 1).ToDictionary(entry => entry.Key, entry => entry.Value[0], StringComparer.Ordinal);
        }

        // The id the first argument of a class's [ObjectId] gives, when it is a string literal.
        private static string? IdOf(ClassDeclarationSyntax declared)
        {
            foreach (var attribute in declared.AttributeLists.SelectMany(list => list.Attributes))
            {
                var name = attribute.Name switch
                {
                    QualifiedNameSyntax qualified => qualified.Right.Identifier.ValueText,
                    SimpleNameSyntax simple => simple.Identifier.ValueText,
                    _ => string.Empty,
                };
                if ((name == "ObjectId" || name == "ObjectIdAttribute")
                    && attribute.ArgumentList?.Arguments.FirstOrDefault()?.Expression is LiteralExpressionSyntax literal
                    && literal.IsKind(SyntaxKind.StringLiteralExpression))
                {
                    return literal.Token.ValueText;
                }
            }

            return null;
        }

        private static string FullName(ClassDeclarationSyntax declared)
        {
            var parts = new List<string>();
            for (SyntaxNode? node = declared; node != null; node = node.Parent)
            {
                switch (node)
                {
                    case TypeDeclarationSyntax type:
                        parts.Add(type.Identifier.ValueText);
                        break;
                    case BaseNamespaceDeclarationSyntax space:
                        parts.Add(space.Name.ToString());
                        break;
                }
            }

            parts.Reverse();
            return "global::" + string.Join(".", parts);
        }

        // Whether any of the map's code names a member, as text: a mention in a comment counts too, which costs only the table.
        private static bool Names(MapProject project, string member)
        {
            return CompiledFiles.Sources(project, project.BuildFolder).Any(path => CompiledFiles.ReadSource(path).Contains(member, StringComparison.Ordinal));
        }

        private static void Lookup(StringBuilder text, HashSet<string> names, string name, string summary, string kind, IReadOnlyDictionary<string, string> classes, int typeId)
        {
            var member = Member(names, name);
            var lookup = $"global::Moonwell.{kind}.Named({Quoted(name)})";
            text.Append($"            /// <summary>{summary}</summary>\n");
            text.Append(classes.TryGetValue(typeId.ToRawcode(), out var type)
                ? $"            public static {type}? {member} => (object?){lookup} as {type};\n"
                : $"            public static global::Moonwell.{kind}? {member} => {lookup};\n");
        }

        private static string Describe(int typeId, float x, float y) =>
            $"{Escape(typeId.ToRawcode())} at ({Math.Round(x).ToString(CultureInfo.InvariantCulture)}, {Math.Round(y).ToString(CultureInfo.InvariantCulture)}).";

        private static void Open(StringBuilder text, string name, string summary)
        {
            text.Append($"        /// <summary>{summary}</summary>\n");
            text.Append($"        public static class {name}\n        {{\n");
        }

        private static void Close(StringBuilder text)
        {
            text.Append("        }\n\n");
        }

        // A C# identifier for a name: letters, digits and _ of ASCII kept, anything else _, a leading digit or a keyword
        // guarded, and a name already taken in the class (or the class's own) given _2, _3 and so on.
        private static string Member(HashSet<string> taken, string name)
        {
            var chars = name.Select(c => c < 128 && (char.IsLetterOrDigit(c) || c == '_') ? c : '_').ToArray();
            var member = new string(chars);
            if (member.Length == 0 || char.IsDigit(member[0]))
            {
                member = "_" + member;
            }

            if (SyntaxFacts.GetKeywordKind(member) != SyntaxKind.None || SyntaxFacts.GetContextualKeywordKind(member) != SyntaxKind.None)
            {
                member = "_" + member;
            }

            var unique = member;
            for (var n = 2; !taken.Add(unique); n++)
            {
                unique = member + "_" + n.ToString(CultureInfo.InvariantCulture);
            }

            return unique;
        }

        private static string Real(float value) => LuaReal(value) + "f";

        private static string LuaReal(float value) => value.ToString("R", CultureInfo.InvariantCulture);

        private static string Quoted(string text) => SymbolDisplay.FormatLiteral(text, true);

        private static string Escape(string text) => text.Replace("&", "&amp;", StringComparison.Ordinal).Replace("<", "&lt;", StringComparison.Ordinal).Replace(">", "&gt;", StringComparison.Ordinal);
    }
}
