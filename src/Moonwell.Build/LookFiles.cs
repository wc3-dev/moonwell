using System.Globalization;
using System.Text;
using Microsoft.CodeAnalysis.CSharp;
using Moonwell.GameData;

namespace Moonwell.Build
{
    /// <summary>
    /// The copies a map lists in a <c>.looks.csv</c> beside a texture in its assets (decisions 320 to 324): a piece of the
    /// texture (mirrored when left is greater than right), multiplied by a colour, cut round, and for a bar 64 step copies of
    /// its left part; with no texture of its name, in the assets or the game, each row is a flat colour. The game tints and cuts
    /// only in simple frames, a layer of their own, so the build makes these as files of their own (decision 320). Before the
    /// compile it writes <c>Looks.g.cs</c>, a class per file with each copy's path (<c>Looks.UITargetingFrame.PlayerFrame</c>).
    /// </summary>
    public static class LookFiles
    {
        /// <summary>The file's name in the generated folder, which the map's project compiles.</summary>
        public const string FileName = "Looks.g.cs";

        /// <summary>The end of a looks table's file name.</summary>
        public const string Extension = ".looks.csv";

        /// <summary>How many step copies a bar's look has; a ProgressBar shows the one nearest its share (decision 322).</summary>
        public const int BarSteps = 64;

        // A flat colour's file is this many pixels on a side.
        private const int FlatSide = 8;

        private static readonly string[] Columns = { "Name", "Left", "Top", "Right", "Bottom", "Color", "Round", "Bar" };

        /// <summary>Writes <c>Looks.g.cs</c> into the generated folder, or deletes one left from an earlier build when the assets hold no looks table.</summary>
        /// <param name="project">The map project.</param>
        /// <exception cref="BuildException">A table cannot be read; the message names it and its line.</exception>
        public static void WriteNames(MapProject project)
        {
            var path = Path.Combine(project.GeneratedFolder, FileName);
            var tables = Read(project);
            if (tables.Count == 0)
            {
                if (File.Exists(path))
                {
                    File.Delete(path);
                }

                return;
            }

            Directory.CreateDirectory(project.GeneratedFolder);
            File.WriteAllText(path, Names(tables));
        }

        /// <summary>The C# of the typed names: a class per table with a constant per row, and <c>Round</c> when a row is cut round.</summary>
        /// <param name="tables">The tables, as <see cref="Read"/> gives them.</param>
        /// <returns>The file's text.</returns>
        public static string Names(IReadOnlyList<Table> tables)
        {
            var text = new StringBuilder();
            text.Append("// Generated by Moonwell's build from the .looks.csv files in assets\\. Do not edit; every build writes it anew.\n");
            text.Append("namespace Moonwell\n{\n");
            text.Append("    /// <summary>The copies the .looks.csv files in the assets list, a class for each file and each copy's path in the map.</summary>\n");
            text.Append("    public static class Looks\n    {\n");
            foreach (var table in tables)
            {
                text.Append($"        /// <summary>The copies of assets\\{table.File}.</summary>\n");
                text.Append($"        public static class {table.ClassName}\n        {{\n");
                foreach (var row in table.Rows)
                {
                    text.Append($"            /// <summary>The copy {row.Name}.</summary>\n");
                    text.Append($"            public const string {row.Member} = {Literal(CopyPath(table, row))};\n");
                }

                text.Append("        }\n\n");
            }

            text.Append("        /// <summary>The round copy of an icon whose .looks.csv has a row cut round, the first such row; any other path as it is.</summary>\n");
            text.Append("        /// <param name=\"path\">The icon's path as the game gives it, in any case.</param>\n");
            text.Append("        public static string Round(string path)\n        {\n");
            var rounds = tables.Select(table => (Table: table, Row: table.Rows.FirstOrDefault(row => row.Round))).Where(pair => pair.Row != null).ToList();
            if (rounds.Count > 0)
            {
                text.Append("            var key = path.ToLowerInvariant();\n");
                foreach (var (table, row) in rounds)
                {
                    text.Append($"            if (key == {Literal((table.Base + ".blp").ToLowerInvariant())})\n            {{\n");
                    text.Append($"                return {table.ClassName}.{row!.Member};\n            }}\n\n");
                }
            }

            text.Append("            return path;\n        }\n    }\n}\n");
            return text.ToString();
        }

        /// <summary>A copy's path in the map: the texture's path and the row's name, <c>.Bar</c> before the extension for a bar's look, which a ProgressBar cuts.</summary>
        public static string CopyPath(Table table, Row row)
        {
            return table.Base + "." + row.Member + (row.Bar ? ".Bar" : string.Empty) + ".blp";
        }

        /// <summary>A bar's step copy: its left <paramref name="step"/> 64ths, at the look's path with the step after <c>.Bar</c>.</summary>
        public static string StepPath(Table table, Row row, int step)
        {
            return table.Base + "." + row.Member + ".Bar" + step.ToString(CultureInfo.InvariantCulture) + ".blp";
        }

        /// <summary>Reads every <c>.looks.csv</c> in the assets, in the order of their paths.</summary>
        /// <param name="project">The map project.</param>
        /// <returns>The tables; none when there is no assets folder.</returns>
        /// <exception cref="BuildException">A table cannot be read, or two make the same class.</exception>
        public static List<Table> Read(MapProject project)
        {
            var tables = new List<Table>();
            if (!Directory.Exists(project.AssetsFolder))
            {
                return tables;
            }

            var classes = new Dictionary<string, string>(StringComparer.Ordinal);
            foreach (var file in Directory.GetFiles(project.AssetsFolder, "*" + Extension, SearchOption.AllDirectories)
                .Select(file => Path.GetRelativePath(project.AssetsFolder, file).Replace('/', '\\'))
                .OrderBy(file => file, StringComparer.Ordinal))
            {
                string text;
                try
                {
                    text = File.ReadAllText(Path.Combine(project.AssetsFolder, file));
                }
                catch (Exception failure) when (failure is IOException or UnauthorizedAccessException)
                {
                    throw new BuildException($@"cannot read assets\{file}: {failure.Message}");
                }

                var table = Parse(file, text);
                if (classes.TryGetValue(table.ClassName, out var other))
                {
                    throw new BuildException($@"assets\{other} and assets\{file} both make Looks.{table.ClassName}; rename one");
                }

                classes[table.ClassName] = file;
                tables.Add(table);
            }

            return tables;
        }

        /// <summary>Reads one table.</summary>
        /// <param name="file">Its path in the assets, <c>war3mapImported\UI-TargetingFrame.looks.csv</c>.</param>
        /// <param name="text">Its text.</param>
        /// <returns>The table.</returns>
        /// <exception cref="BuildException">A column, name or value is wrong; the message names the line.</exception>
        public static Table Parse(string file, string text)
        {
            var shown = @"assets\" + file;
            var stem = file[..^Extension.Length];
            var table = new Table(file, stem, DataWriter.Name(Path.GetFileName(stem), shown, "its file name"));
            var lines = DataWriter.CsvTable.Parse(text, shown);
            if (lines.Count == 0)
            {
                throw new BuildException($"{shown} has no header line");
            }

            var header = lines[0];
            var at = new Dictionary<string, int>(StringComparer.OrdinalIgnoreCase);
            for (var i = 0; i < header.Cells.Count; i++)
            {
                var column = header.Cells[i].Trim();
                if (!Columns.Contains(column, StringComparer.OrdinalIgnoreCase))
                {
                    throw new BuildException($"{shown}:{header.Line}: no column {column}; a looks table has {string.Join(", ", Columns)}");
                }

                if (!at.TryAdd(column, i))
                {
                    throw new BuildException($"{shown}:{header.Line}: two columns {column}");
                }
            }

            if (!at.ContainsKey("Name"))
            {
                throw new BuildException($"{shown}:{header.Line}: no column Name");
            }

            var members = new HashSet<string>(StringComparer.Ordinal);
            foreach (var (line, cells) in lines.Skip(1))
            {
                var where = $"{shown}:{line}";
                if (cells.Count > header.Cells.Count)
                {
                    throw new BuildException($"{where}: {cells.Count} values, and the header names {header.Cells.Count} columns");
                }

                string Cell(string column) => at.TryGetValue(column, out var index) && index < cells.Count ? cells[index].Trim() : string.Empty;

                var name = Cell("Name");
                var member = DataWriter.Name(name, where, "the name");
                if (!members.Add(member))
                {
                    throw new BuildException($"{where}: two rows make the name {member}");
                }

                var sides = new[] { "Left", "Top", "Right", "Bottom" }.Select(Cell).ToArray();
                Region? region = null;
                if (sides.Any(side => side.Length > 0))
                {
                    if (sides.Any(side => side.Length == 0))
                    {
                        throw new BuildException($"{where}: a piece needs all of Left, Top, Right and Bottom");
                    }

                    var values = sides.Select(side => Fraction(side, where)).ToArray();
                    if (values[0] == values[2] || values[1] == values[3])
                    {
                        throw new BuildException($"{where}: the piece has no width or no height");
                    }

                    region = new Region(values[0], values[1], values[2], values[3]);
                }

                table.Rows.Add(new Row(name, member, line, region, Colour(Cell("Color"), where), YesNo(Cell("Round"), "Round", where), YesNo(Cell("Bar"), "Bar", where)));
            }

            return table;
        }

        /// <summary>Writes every table's copies into the staged map, from the texture in the assets, else the game's own (Classic) at that path, else as flat colours.</summary>
        /// <param name="project">The map project, its assets staged.</param>
        /// <param name="log">Where notes go.</param>
        /// <returns>The copies' paths in the map, for the import list.</returns>
        /// <exception cref="BuildException">A texture cannot be read, a row does not fit a flat colour, or a copy would replace a file of the map.</exception>
        public static List<string> Make(MapProject project, TextWriter log)
        {
            var made = new List<string>();
            var tables = Read(project);
            GameFiles? game = null;
            try
            {
                foreach (var table in tables)
                {
                    var source = Source(project, table, ref game);
                    foreach (var row in table.Rows)
                    {
                        var look = source == null ? Flat(table, row) : Look(source.Value, row);
                        Write(project, CopyPath(table, row), look, made);
                        if (row.Bar)
                        {
                            for (var step = 1; step < BarSteps; step++)
                            {
                                Write(project, StepPath(table, row, step), Cut(look, step), made);
                            }
                        }
                    }
                }
            }
            finally
            {
                game?.Dispose();
            }

            if (made.Count > 0)
            {
                log.WriteLine($"moonwell: made {made.Count} copies from {tables.Count} looks table{(tables.Count == 1 ? string.Empty : "s")}");
            }

            return made;
        }

        // The texture a table copies: assets\<stem>.png or .blp, else the game's <stem>.blp; null for flat colours.
        private static Picture? Source(MapProject project, Table table, ref GameFiles? game)
        {
            var shown = @"assets\" + table.File;
            foreach (var extension in new[] { ".png", ".blp" })
            {
                var file = Path.Combine(project.AssetsFolder, table.Base + extension);
                if (File.Exists(file))
                {
                    var (width, height, pixels) = Images.Read(file, @"assets\" + table.Base + extension);
                    return new Picture(width, height, pixels);
                }
            }

            if (File.Exists(Path.Combine(project.AssetsFolder, table.Base + ".tga")) || File.Exists(Path.Combine(project.AssetsFolder, table.Base + ".dds")))
            {
                throw new BuildException($"{shown}: the build copies PNG and BLP textures only");
            }

            try
            {
                game ??= GameFiles.Open(GameInstall.Require(null));
            }
            catch (Exception failure) when (failure is IOException or InvalidDataException)
            {
                throw new BuildException($"{shown}: assets has no {table.Base}.png or .blp, and the game's files cannot be read to look for one ({failure.Message})");
            }

            var bytes = game.Read(table.Base + ".blp", "sd");
            if (bytes == null)
            {
                return null;
            }

            var (w, h, p) = Images.ReadGame(bytes, $"the game's {table.Base}.blp");
            return new Picture(w, h, p);
        }

        // A flat colour: an 8 by 8 square of the row's colour.
        private static Picture Flat(Table table, Row row)
        {
            var where = $@"assets\{table.File}:{row.Line}";
            if (row.Color == null || row.Region != null || row.Round || row.Bar)
            {
                throw new BuildException($@"{where}: neither assets nor the game has {table.Base}.png or .blp, so each row is a flat colour, with a Name and a Color only");
            }

            var pixels = new byte[FlatSide * FlatSide * 4];
            for (var i = 0; i < pixels.Length; i += 4)
            {
                (pixels[i], pixels[i + 1], pixels[i + 2], pixels[i + 3]) = (row.Color.Value.B, row.Color.Value.G, row.Color.Value.R, 255);
            }

            return new Picture(FlatSide, FlatSide, pixels);
        }

        /// <summary>A row's copy of a texture: its piece at the next power of two of the piece's size, multiplied by its colour, then cut round.</summary>
        /// <param name="source">The texture, blue, green, red and alpha.</param>
        /// <param name="row">The row.</param>
        /// <returns>The copy.</returns>
        public static Picture Look(Picture source, Row row)
        {
            var region = row.Region ?? new Region(0, 0, 1, 1);
            var width = PowerOfTwo(Math.Abs(region.Right - region.Left) * source.Width);
            var height = PowerOfTwo(Math.Abs(region.Bottom - region.Top) * source.Height);
            var pixels = new byte[width * height * 4];
            for (var y = 0; y < height; y++)
            {
                var v = region.Top + ((region.Bottom - region.Top) * (y + 0.5) / height);
                for (var x = 0; x < width; x++)
                {
                    var u = region.Left + ((region.Right - region.Left) * (x + 0.5) / width);
                    Sample(source, u, v, pixels, ((y * width) + x) * 4);
                }
            }

            var look = new Picture(width, height, pixels);
            if (row.Color is { } colour)
            {
                for (var i = 0; i < pixels.Length; i += 4)
                {
                    pixels[i] = (byte)Math.Round(pixels[i] * colour.B / 255.0);
                    pixels[i + 1] = (byte)Math.Round(pixels[i + 1] * colour.G / 255.0);
                    pixels[i + 2] = (byte)Math.Round(pixels[i + 2] * colour.R / 255.0);
                }
            }

            if (row.Round)
            {
                CutRound(look);
            }

            return look;
        }

        /// <summary>A bar's step copy: the look's left <paramref name="step"/> 64ths, at the next power of two of that width.</summary>
        public static Picture Cut(Picture look, int step)
        {
            var share = (double)step / BarSteps;
            var width = PowerOfTwo(look.Width * share);
            var pixels = new byte[width * look.Height * 4];
            for (var y = 0; y < look.Height; y++)
            {
                var v = (y + 0.5) / look.Height;
                for (var x = 0; x < width; x++)
                {
                    Sample(look, share * (x + 0.5) / width, v, pixels, ((y * width) + x) * 4);
                }
            }

            return new Picture(width, look.Height, pixels);
        }

        // The circle (an ellipse when not square) inside the picture keeps its alpha, with a soft edge one pixel wide; the rest is see-through.
        private static void CutRound(Picture picture)
        {
            var rx = picture.Width / 2.0;
            var ry = picture.Height / 2.0;
            for (var y = 0; y < picture.Height; y++)
            {
                for (var x = 0; x < picture.Width; x++)
                {
                    var dx = (x + 0.5 - rx) / rx;
                    var dy = (y + 0.5 - ry) / ry;
                    var outside = (Math.Sqrt((dx * dx) + (dy * dy)) - 1) * Math.Min(rx, ry);
                    var keep = Math.Clamp(0.5 - outside, 0, 1);
                    var i = (((y * picture.Width) + x) * 4) + 3;
                    picture.Pixels[i] = (byte)Math.Round(picture.Pixels[i] * keep);
                }
            }
        }

        // Bilinear, the edges held, at u and v from 0 to 1 across the picture.
        private static void Sample(Picture source, double u, double v, byte[] into, int at)
        {
            var fx = Math.Clamp((u * source.Width) - 0.5, 0, source.Width - 1);
            var fy = Math.Clamp((v * source.Height) - 0.5, 0, source.Height - 1);
            var x0 = (int)fx;
            var y0 = (int)fy;
            var x1 = Math.Min(x0 + 1, source.Width - 1);
            var y1 = Math.Min(y0 + 1, source.Height - 1);
            var ax = fx - x0;
            var ay = fy - y0;
            for (var c = 0; c < 4; c++)
            {
                var top = (source.At(x0, y0, c) * (1 - ax)) + (source.At(x1, y0, c) * ax);
                var bottom = (source.At(x0, y1, c) * (1 - ax)) + (source.At(x1, y1, c) * ax);
                into[at + c] = (byte)Math.Round((top * (1 - ay)) + (bottom * ay));
            }
        }

        private static void Write(MapProject project, string path, Picture picture, List<string> made)
        {
            var target = Path.Combine(project.StagedFolder, path);
            if (File.Exists(target))
            {
                throw new BuildException($"the looks copy {path} would replace a file of the map's; rename the row or the file");
            }

            Images.Write(target, picture.Width, picture.Height, picture.Pixels);
            made.Add(path);
        }

        private static int PowerOfTwo(double pixels)
        {
            var side = 1;
            while (side < Math.Round(pixels) && side < 4096)
            {
                side *= 2;
            }

            return side;
        }

        private static double Fraction(string text, string where)
        {
            if (!double.TryParse(text, NumberStyles.Float, CultureInfo.InvariantCulture, out var value) || value < 0 || value > 1)
            {
                throw new BuildException($"{where}: {text} is not a number from 0 to 1; a piece's sides are shares of the texture, as WoW's TexCoords");
            }

            return value;
        }

        private static Rgb? Colour(string text, string where)
        {
            var digits = text.TrimStart('#');
            if (digits.Length == 0)
            {
                return null;
            }

            if (digits.Length != 6 || !int.TryParse(digits, NumberStyles.HexNumber, CultureInfo.InvariantCulture, out var value))
            {
                throw new BuildException($"{where}: the colour {text} is not six hex digits, red, green and blue, as 00ff00");
            }

            return new Rgb((byte)(value >> 16), (byte)(value >> 8), (byte)value);
        }

        private static bool YesNo(string text, string column, string where)
        {
            return text.ToLowerInvariant() switch
            {
                "yes" => true,
                "no" or "" => false,
                _ => throw new BuildException($"{where}: {column} is yes, no or empty, not {text}"),
            };
        }

        private static string Literal(string text)
        {
            return SymbolDisplay.FormatLiteral(text, true);
        }

        /// <summary>A looks table: its file in the assets, the texture's path without extension, its class and rows.</summary>
        public sealed record Table(string File, string Base, string ClassName)
        {
            /// <summary>The rows, in the file's order.</summary>
            public List<Row> Rows { get; } = new List<Row>();
        }

        /// <summary>A row of a looks table: one copy.</summary>
        public sealed record Row(string Name, string Member, int Line, Region? Region, Rgb? Color, bool Round, bool Bar);

        /// <summary>A piece of a texture, each side a share of it from 0 to 1, as WoW's TexCoords.</summary>
        public sealed record Region(double Left, double Top, double Right, double Bottom);

        /// <summary>A colour a copy is multiplied by.</summary>
        public readonly record struct Rgb(byte R, byte G, byte B);

        /// <summary>Pixels as blue, green, red and alpha, row by row from the top.</summary>
        public readonly record struct Picture(int Width, int Height, byte[] Pixels)
        {
            /// <summary>One channel of a pixel: 0 blue, 1 green, 2 red, 3 alpha.</summary>
            public byte At(int x, int y, int channel)
            {
                return Pixels[(((y * Width) + x) * 4) + channel];
            }
        }
    }
}
